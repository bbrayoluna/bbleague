-- Registra las descargas y subidas de rosters.
-- Ejecutar despues de 026_tournament_max_player_skills.sql.

begin;

create table public.roster_activity (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid()
    references public.users(id) on delete cascade,
  username text not null,
  team_name text not null check (length(trim(team_name)) > 0),
  team_type text not null check (length(trim(team_type)) > 0),
  tournament_id bigint references public.tournaments(id) on delete set null,
  tournament_name text,
  action text not null check (action in ('download', 'upload')),
  created_at timestamptz not null default now()
);

create index roster_activity_user_created_idx
  on public.roster_activity (user_id, created_at desc);
create index roster_activity_tournament_idx
  on public.roster_activity (tournament_id, created_at desc);

create or replace function public.set_roster_activity_context()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  select username
  into new.username
  from public.users
  where id = new.user_id;

  if new.username is null then
    raise exception 'No se pudo identificar al usuario del roster'
      using errcode = '23503';
  end if;

  if new.tournament_id is null then
    new.tournament_name := null;
  else
    select format('%s (%s)', name, year)
    into new.tournament_name
    from public.tournaments
    where id = new.tournament_id;

    if new.tournament_name is null then
      raise exception 'No existe el torneo indicado'
        using errcode = '23503';
    end if;
  end if;

  return new;
end;
$$;

revoke all on function public.set_roster_activity_context() from public, anon, authenticated;

create trigger roster_activity_set_context
before insert on public.roster_activity
for each row execute function public.set_roster_activity_context();

alter table public.roster_activity enable row level security;

grant select, insert on public.roster_activity to authenticated;
grant usage on sequence public.roster_activity_id_seq to authenticated;

create policy "users can read their roster activity"
  on public.roster_activity for select
  to authenticated
  using (user_id = auth.uid());

create policy "users can record their roster activity"
  on public.roster_activity for insert
  to authenticated
  with check (
    user_id = auth.uid()
    and (
      tournament_id is null
      or exists (
        select 1
        from public.tournament_users
        where tournament_id = roster_activity.tournament_id
          and user_id = auth.uid()
      )
    )
  );

commit;
