create policy "public can read users"
  on public.users for select using (true);

create policy "public can read active races"
  on public.races for select using (active = true);

create policy "public can read tournaments"
  on public.tournaments for select using (true);

create policy "authenticated users can create tournaments"
  on public.tournaments for insert
  with check (auth.uid() is not null);

create policy "public can read tournament users"
  on public.tournament_users for select using (true);
create policy "users can register themselves"
  on public.tournament_users for insert
  with check (user_id = auth.uid());
create policy "users can update their registration"
  on public.tournament_users for update
  using (user_id = auth.uid())
  with check (user_id = auth.uid());
create policy "users can delete their registration"
  on public.tournament_users for delete using (user_id = auth.uid());

create policy "public can read rounds"
  on public.rounds for select using (true);

create policy "public can read matches"
  on public.matches for select using (true);

create policy "public can read results"
  on public.results for select using (true);
create policy "participants can submit results"
  on public.results for insert
  with check (
    submitted_by = auth.uid()
    and exists (
      select 1
      from public.matches m
      join public.tournament_users tpa on tpa.id = m.tournament_user_a_id
      join public.tournament_users tpb on tpb.id = m.tournament_user_b_id
      where m.id = match_id
        and (tpa.user_id = auth.uid() or tpb.user_id = auth.uid())
    )
  );
create policy "submitters can update results"
  on public.results for update
  using (submitted_by = auth.uid())
  with check (submitted_by = auth.uid());
